fn file<'a>(data: &'a proto::GitDiffData, path: &str) -> &'a proto::FileDiff {
    data.files
        .iter()
        .find(|f| f.file_path == path)
        .unwrap_or_else(|| {
            panic!(
                "no {path} in {:?}",
                data.files.iter().map(|f| &f.file_path).collect::<Vec<_>>()
            )
        })
}

fn kind(f: &proto::FileDiff) -> &'static str {
    use proto::git_file_status::Status as S;
    match f.status.as_ref().and_then(|s| s.status.as_ref()).unwrap() {
        S::NewFile(_) => "new",
        S::Modified(_) => "modified",
        S::Deleted(_) => "deleted",
        S::Renamed(_) => "renamed",
        S::Copied(_) => "copied",
        S::Untracked(_) => "untracked",
        S::Conflicted(_) => "conflicted",
    }
}

fn staged(f: &proto::FileDiff) -> proto::FileStagedState {
    proto::FileStagedState::try_from(f.staged).unwrap()
}

#[test]
fn hunks_carry_line_numbers_and_the_no_newline_marker() {
    let diff = "diff --git a/f b/f\n--- a/f\n+++ b/f\n@@ -1,3 +1,3 @@ fn x\n one\n-two\n+TWO\n three\n\\ No newline at end of file\n";
    let hunks = parse_diff_hunks(diff).unwrap();
    assert_eq!(hunks.len(), 1);
    let h = &hunks[0];
    assert_eq!(
        (
            h.old_start_line,
            h.old_line_count,
            h.new_start_line,
            h.new_line_count
        ),
        (1, 3, 1, 3)
    );
    let shape: Vec<_> = h
        .lines
        .iter()
        .map(|l| {
            (
                l.line_type,
                l.old_line_number,
                l.new_line_number,
                l.text.as_str(),
            )
        })
        .collect();
    use proto::DiffLineType as T;
    assert_eq!(
        shape,
        vec![
            (T::Context as i32, Some(1), Some(1), "one"),
            (T::Delete as i32, Some(2), None, "two"),
            (T::Add as i32, None, Some(2), "TWO"),
            (T::Context as i32, Some(3), Some(3), "three"),
        ]
    );
    assert!(
        h.lines[3].no_trailing_newline,
        "the marker belongs to the line before it"
    );
    assert!(!h.lines[0].no_trailing_newline);
    // A single-line range has an implicit count of 1.
    let one = parse_diff_hunks("@@ -5 +5 @@\n-a\n+b\n").unwrap();
    assert_eq!((one[0].old_line_count, one[0].new_line_count), (1, 1));
    assert!(parse_diff_hunks("@@ garbage\n").is_err());
}

#[test]
fn diff_size_follows_the_render_limits() {
    let line = |t: proto::DiffLineType, text: &str| proto::DiffLine {
        line_type: t as i32,
        text: text.into(),
        ..Default::default()
    };
    let hunk = |lines| proto::DiffHunk {
        lines,
        ..Default::default()
    };
    assert_eq!(compute_diff_size(&[], 10), proto::DiffSize::Normal);
    assert_eq!(
        compute_diff_size(&[], MAX_DIFF_SIZE + 1),
        proto::DiffSize::UnrenderableDiffTooLarge
    );
    assert_eq!(compute_diff_size(&[], 2_187_500), proto::DiffSize::Large);
    let long = hunk(vec![line(proto::DiffLineType::Add, &"x".repeat(5001))]);
    assert_eq!(compute_diff_size(&[long], 10), proto::DiffSize::Large);
    let many_dels = hunk(
        (0..8001)
            .map(|_| line(proto::DiffLineType::Delete, "d"))
            .collect(),
    );
    assert_eq!(
        compute_diff_size(&[many_dels], 10),
        proto::DiffSize::UnrenderableDiffTooLarge
    );
    let many_adds = hunk(
        (0..10_001)
            .map(|_| line(proto::DiffLineType::Add, "a"))
            .collect(),
    );
    assert_eq!(compute_diff_size(&[many_adds], 10), proto::DiffSize::Large);
}

#[test]
fn autogenerated_files_are_recognised() {
    for p in [
        "Cargo.lock",
        "a/b/yarn.lock",
        "x.log",
        "app.min.js",
        "api.generated.ts",
        "src/__generated__/a.rs",
    ] {
        assert!(is_file_autogenerated(Path::new(p), None), "{p}");
    }
    assert!(!is_file_autogenerated(
        Path::new("src/main.rs"),
        Some("fn main() {}")
    ));
    assert!(is_file_autogenerated(
        Path::new("a.rs"),
        Some("// Code generated by tool\nfn x(){}")
    ));
}

#[test]
fn base_content_over_the_wire_budget_is_withheld_and_marks_the_file() {
    let f = plain_file(
        Path::new("a"),
        &GitFileStatus::Modified,
        None,
        false,
        proto::DiffSize::Normal,
    );
    let big = "x".repeat(MAX_DIFF_SIZE + 1);
    let out = finish(f.clone(), Some(big));
    assert_eq!(out.content_at_base, None);
    assert_eq!(out.size, proto::DiffSize::UnrenderableFileTooLarge as i32);
    let ok = finish(f.clone(), Some("body".into()));
    assert_eq!(ok.content_at_base.as_deref(), Some("body"));
    let mut bin = f;
    bin.is_binary = true;
    assert_eq!(finish(bin, Some("body".into())).content_at_base, None);
}

