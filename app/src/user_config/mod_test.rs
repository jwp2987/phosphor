#[cfg(feature = "local_fs")]
#[test]
fn test_materialize_default_worktree_config_bakes_repo_and_pane_type_only() {
    let template = include_str!("../../resources/tab_configs/default_worktree.toml");
    let repo_path = "/tmp/example-repo";
    let (toml_content, tab_config) =
        materialize_default_worktree_config(template, "Worktree: example-repo", repo_path, "agent")
            .expect("expected template materialization to succeed");

    assert!(toml_content.contains("name = \"Worktree: example-repo\""));
    assert!(toml_content.contains(repo_path));
    assert!(toml_content.contains("type = \"agent\""));
    assert!(toml_content.contains("{{autogenerated_branch_name}}"));
    // The worktree path is filled in (and quoted) at render time, never baked (#878).
    assert!(toml_content.contains("{{worktree_path}}"));
    assert!(
        !toml_content.contains(
            &generated_worktree_repo_dir(Path::new(repo_path))
                .display()
                .to_string()
        )
    );
    assert!(!toml_content.contains("{{repo}}"));
    assert!(!toml_content.contains("{{pane_type}}"));
    assert!(!toml_content.contains("{{worktree_path_prefix}}"));
    assert!(!toml_content.contains("[params.repo]"));
    assert!(!toml_content.contains("[params.pane_type]"));

    assert!(tab_config.params.is_empty());
    assert_eq!(tab_config.name, "Worktree: example-repo");
    assert_eq!(tab_config.panes.len(), 1);
    assert_eq!(tab_config.panes[0].directory.as_deref(), Some(repo_path));
    assert_eq!(
        tab_config.panes[0].pane_type,
        Some(TabConfigPaneType::Agent)
    );
}

#[cfg(feature = "local_fs")]
#[test]
fn test_materialized_default_worktree_config_renders_full_worktree_path() {
    let template = include_str!("../../resources/tab_configs/default_worktree.toml");
    let repo_path = "/tmp/example-repo";
    let (_, tab_config) =
        materialize_default_worktree_config(template, "Worktree: example-repo", repo_path, "agent")
            .expect("expected template materialization to succeed");

    let (_, pane_template) = render_tab_config(&tab_config, &HashMap::new(), Some("my-feature"));

    if let PaneTemplateType::PaneTemplate { commands, .. } = pane_template {
        let expected_worktree_path = expected_worktree_path_word(repo_path, "my-feature");
        assert_eq!(commands.len(), 2);
        assert_eq!(
            commands[0].exec,
            format!("git worktree add -b my-feature -- {expected_worktree_path}")
        );
        assert_eq!(commands[1].exec, format!("cd {expected_worktree_path}"));
    } else {
        panic!("expected terminal pane template");
    }
}

#[cfg(feature = "local_fs")]
fn expected_worktree_path_word(repo_path: &str, branch: &str) -> String {
    let path = generated_worktree_repo_dir(Path::new(repo_path))
        .join(branch)
        .display()
        .to_string();
    portable_shell_word(&path)
        .expect("test paths are portable")
        .into_owned()
}

#[cfg(feature = "local_fs")]
fn materialized_commands(template: &str, repo_path: &str) -> Vec<String> {
    let (_, tab_config) =
        materialize_default_worktree_config(template, "Worktree", repo_path, "terminal")
            .expect("expected template materialization to succeed");
    match render_tab_config(&tab_config, &HashMap::new(), Some("my-feature")).1 {
        PaneTemplateType::PaneTemplate { commands, .. } => {
            commands.into_iter().map(|command| command.exec).collect()
        }
        PaneTemplateType::PaneBranchTemplate { .. } => panic!("expected terminal pane template"),
    }
}

/// The template shipped before #878 is still on users' disks (it is copied once and never
/// overwritten); its `"{{worktree_path_prefix}}{{autogenerated_branch_name}}"` and a
/// customized `"{{repo}}"` put the repo name inside double quotes, where `$(...)` ran.
#[cfg(feature = "local_fs")]
#[test]
fn test_materialized_worktree_commands_quote_hostile_repo_names() {
    const PRE_878_TEMPLATE: &str = r#"
name = "Worktree"

[[panes]]
id = "main"
type = "{{pane_type}}"
directory = "{{repo}}"
commands = [
  "git worktree add -b {{autogenerated_branch_name}} \"{{worktree_path_prefix}}{{autogenerated_branch_name}}\"",
  "cd \"{{worktree_path_prefix}}{{autogenerated_branch_name}}\"",
  "echo \"{{repo}}\" {{repo}}",
]

[params.repo]
type = "repo"

[params.pane_type]
type = "text"
default = "terminal"
"#;
    let shipped = include_str!("../../resources/tab_configs/default_worktree.toml");
    for name in [
        "$(touch pwned)",
        "`touch pwned`",
        "a\"; touch pwned; echo \"",
        "it's",
    ] {
        let repo_path = format!("/tmp/{name}");
        let path_word = expected_worktree_path_word(&repo_path, "my-feature");
        let repo_word = portable_shell_word(&repo_path).unwrap().into_owned();
        assert!(repo_word.starts_with('\'') || repo_word.starts_with('"'));

        assert_eq!(
            materialized_commands(shipped, &repo_path),
            [
                format!("git worktree add -b my-feature -- {path_word}"),
                format!("cd {path_word}"),
            ],
            "shipped template, repo {name:?}"
        );
        assert_eq!(
            materialized_commands(PRE_878_TEMPLATE, &repo_path),
            [
                format!("git worktree add -b my-feature {path_word}"),
                format!("cd {path_word}"),
                format!("echo {repo_word} {repo_word}"),
            ],
            "pre-#878 template, repo {name:?}"
        );
    }

    // A placeholder inside the template's own quotes cannot be quoted safely.
    let quoted_inside =
        PRE_878_TEMPLATE.replace("echo \\\"{{repo}}\\\" {{repo}}", "echo '{{repo}}/x'");
    assert_ne!(quoted_inside, PRE_878_TEMPLATE);
    assert!(
        materialize_default_worktree_config(&quoted_inside, "W", "/tmp/$(touch pwned)", "terminal")
            .is_err()
    );

    // A repo path with no portable spelling is refused when a command needs it, as is one
    // that the render would substitute into (closing the quotes from inside).
    assert!(
        materialize_default_worktree_config(
            PRE_878_TEMPLATE,
            "W",
            "/tmp/{{worktree_path}}$(touch pwned)",
            "terminal"
        )
        .is_err()
    );
    assert!(
        materialize_default_worktree_config(PRE_878_TEMPLATE, "W", "/tmp/a\rb", "terminal")
            .is_err()
    );
}

