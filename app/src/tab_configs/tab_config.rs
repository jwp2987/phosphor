/// A tab config loaded from a `.toml` file in `~/.warp/tab_configs/`.
///
/// Pane layout is defined with a flat `[[panes]]` array where the first entry
/// is the root and splits reference children by ID.
#[derive(Clone, Debug, Deserialize, Serialize)]
#[serde(deny_unknown_fields)]
pub struct TabConfig {
    /// Display name shown in the + menu.
    pub name: String,
    /// Optional tab title template. Supports `{{ }}` template variables.
    #[serde(default)]
    pub title: Option<String>,
    /// Optional tab color.
    #[serde(default)]
    pub color: Option<AnsiColorIdentifier>,
    /// Flat pane list. The first entry is the root of the pane tree.
    #[serde(default)]
    pub panes: Vec<TabConfigPaneNode>,
    /// Named parameters that the user fills in before the tab opens.
    /// Keys are parameter names (used in `{{ }}` placeholders).
    #[serde(default)]
    pub params: HashMap<String, TabConfigParam>,
    /// The on-disk path this config was loaded from.
    /// Populated during parsing; not serialized into or from the TOML.
    #[serde(skip)]
    pub source_path: Option<PathBuf>,
}

impl TabConfig {
    /// Returns param values using defaults where available, and empty strings for
    /// params with no default.  This is the fallback used when no param-fill UI is shown.
    pub fn default_param_values(&self) -> HashMap<String, String> {
        self.params
            .iter()
            .map(|(name, param)| {
                let value = param.default.clone().unwrap_or_default();
                (name.clone(), value)
            })
            .collect()
    }

    pub(crate) fn is_worktree(&self) -> bool {
        self.panes.iter().any(|pane| {
            pane.commands.as_ref().is_some_and(|commands| {
                commands
                    .iter()
                    .any(|command| command.contains("git worktree"))
            })
        })
    }

    pub(crate) fn uses_autogenerated_branch_name(&self) -> bool {
        self.title
            .as_deref()
            .is_some_and(contains_autogenerated_branch_name)
            || self.panes.iter().any(|pane| {
                pane.directory
                    .as_deref()
                    .is_some_and(contains_autogenerated_branch_name)
                    || pane.commands.as_ref().is_some_and(|commands| {
                        commands
                            .iter()
                            .any(|command| contains_autogenerated_branch_name(command))
                    })
            })
    }
}

/// Renders a [`TabConfig`] with the given param values into a [`PaneTemplateType`]
/// and an optional rendered title.
///
/// - `title` and `directory` receive unquoted param values (quoting would break paths).
/// - `commands` receive each value as one shell word spelled by [`portable_shell_word`]. That
///   spelling is only safe where a shell reads an ordinary argument word, so a command with a
///   substituted placeholder must stay within a conservative whitelist — the placeholder bare
///   or exactly `"{{x}}"`/`'{{x}}'`, other quotes only as closed plain literals with no
///   placeholder inside, and no `$(`, `${`, `$[`, `((`, `<<`, backticks, backslashes, comments
///   or line breaks in that command — or it is refused (#878); see [`render_command`].
/// - `worktree_branch_name`: when `Some`, injected into the template context as the
///   special-cased `autogenerated_branch_name` var so commands can use
///   `{{autogenerated_branch_name}}`.
/// - Commands may also use `{{worktree_path}}`, the generated worktree path for the pane's
///   directory and the worktree branch; see [`WORKTREE_PATH_VAR`].
///
/// A config that cannot be rendered — a structural error, or a command that cannot be made
/// safe — falls back to a single empty terminal. Callers that can tell the user why should
/// use [`try_render_tab_config`] instead.
pub fn render_tab_config(
    config: &TabConfig,
    param_values: &HashMap<String, String>,
    worktree_branch_name: Option<&str>,
) -> (Option<String>, PaneTemplateType) {
    try_render_tab_config(config, param_values, worktree_branch_name).unwrap_or_else(|err| {
        log::warn!(
            "Not running the commands of tab config '{}': {err}",
            config.name
        );
        (None, fallback_pane_template())
    })
}

/// [`render_tab_config`], except that a command which cannot be rendered safely is returned
/// as an error — naming the value that could not be quoted — instead of silently becoming an
/// empty terminal, so the caller can show it (#878). Structural errors in the pane tree still
/// fall back to an empty terminal, as before.
pub fn try_render_tab_config(
    config: &TabConfig,
    param_values: &HashMap<String, String>,
    worktree_branch_name: Option<&str>,
) -> Result<(Option<String>, PaneTemplateType), String> {
    let context = build_template_context(param_values, worktree_branch_name);

    let rendered_title = config
        .title
        .as_deref()
        .map(|t| handlebars::render_template(t, &context));

    let pane_template = match resolve_pane_tree(&config.panes, &context) {
        Ok(template) => template,
        Err(ResolveError::UnsafeCommand(err)) => return Err(err),
        Err(ResolveError::Structure(err)) => {
            log::warn!("Failed to resolve pane tree for '{}': {err}", config.name);
            fallback_pane_template()
        }
    };

    Ok((rendered_title, pane_template))
}

fn fallback_pane_template() -> PaneTemplateType {
    PaneTemplateType::PaneTemplate {
        cwd: PathBuf::new(),
        commands: Vec::new(),
        is_focused: Some(true),
        pane_mode: PaneMode::Terminal,
        shell: None,
    }
}

/// Why a pane tree could not be resolved.
enum ResolveError {
    /// The `[[panes]]` layout is malformed.
    Structure(String),
    /// A command could not be rendered without risking shell injection (#878).
    UnsafeCommand(String),
}

impl From<String> for ResolveError {
    fn from(err: String) -> Self {
        Self::Structure(err)
    }
}

/// The raw (unquoted) template values: the params plus the autogenerated branch name.
fn build_template_context(
    param_values: &HashMap<String, String>,
    worktree_branch_name: Option<&str>,
) -> HashMap<String, String> {
    let mut context = param_values.clone();
    if let Some(name) = worktree_branch_name {
        context.insert(
            AUTOGENERATED_BRANCH_NAME_PARAM.to_string(),
            name.to_string(),
        );
    }
    context
}

/// Adds [`WORKTREE_PATH_VAR`] for a pane whose directory is `directory`, unless a param of
/// that name already supplies it. The branch is the autogenerated name when there is one,
/// otherwise the `worktree_branch_name` param.
fn command_values_for_pane<'a>(
    context: &'a HashMap<String, String>,
    directory: Option<&str>,
) -> Cow<'a, HashMap<String, String>> {
    if context.contains_key(WORKTREE_PATH_VAR) {
        return Cow::Borrowed(context);
    }
    let branch = context
        .get(AUTOGENERATED_BRANCH_NAME_PARAM)
        .or_else(|| context.get(WORKTREE_BRANCH_NAME_PARAM));
    let (Some(directory), Some(branch)) = (directory, branch) else {
        return Cow::Borrowed(context);
    };
    let mut values = context.clone();
    values.insert(
        WORKTREE_PATH_VAR.to_string(),
        generated_worktree_path_string(Path::new(directory), branch),
    );
    Cow::Owned(values)
}

/// Rewrites the worktree path that configs generated before #878 baked into their commands —
/// `"<data dir>/worktrees/<repo name>/{{branch var}}"`, inside double quotes, where a repo
/// name containing `$(...)`, a backtick or `"` was shell syntax — to [`WORKTREE_PATH_VAR`],
/// so reopening such a saved config quotes the path instead of re-running the injection.
/// Only the exact strings those generators produced for this pane's directory are touched;
/// a legacy path under any other directory still has its placeholder inside double quotes,
/// which [`render_command`] refuses.
///
/// Those generators also appended the base branch unquoted. When the rewritten command is
/// the legacy `git worktree add -b {{var}} {{worktree_path}} <base>`, `<base>` must already
/// be a plain word ([`portable_shell_word`] leaves it unchanged); otherwise it is refused.
fn upgrade_legacy_worktree_path<'a>(
    command: &'a str,
    directory: Option<&str>,
) -> Result<Cow<'a, str>, String> {
    let Some(directory) = directory else {
        return Ok(Cow::Borrowed(command));
    };
    let worktree_path_var = handlebars_placeholder(WORKTREE_PATH_VAR);
    let mut command = Cow::Borrowed(command);
    for branch_var in [AUTOGENERATED_BRANCH_NAME_PARAM, WORKTREE_BRANCH_NAME_PARAM] {
        let legacy = format!(
            "\"{}\"",
            generated_worktree_path_string(
                Path::new(directory),
                &handlebars_placeholder(branch_var)
            )
        );
        if !command.contains(&legacy) {
            continue;
        }
        command = Cow::Owned(command.replace(&legacy, &worktree_path_var));
        let legacy_add = format!(
            "git worktree add -b {} {worktree_path_var}",
            handlebars_placeholder(branch_var)
        );
        if let Some(tail) = command.strip_prefix(&legacy_add) {
            let base = tail.trim();
            if !base.is_empty() && portable_shell_word(base).as_deref() != Some(base) {
                return Err(format!(
                    "this worktree config was created by an older version and passes the base \
                     branch {base:?} to the shell unquoted; recreate the config"
                ));
            }
        }
    }
    Ok(command)
}

/// Quote characters in any supported shell, including the typographic ones PowerShell accepts.
const QUOTE_CHARS: [char; 9] = [
    '\'', '"', '\u{2018}', '\u{2019}', '\u{201A}', '\u{201B}', '\u{201C}', '\u{201D}', '\u{201E}',
];

/// Stands for a substituted placeholder in the residual command text that
/// [`render_command`] checks: a private-use character no template plausibly contains.
const PLACEHOLDER_MARK: char = '\u{E000}';
/// Stands for a literal quoted string in the residual text the syntax checks see.
const LITERAL_MARK: char = '\u{E001}';

/// The residual command in the two forms [`render_command`] checks.
struct StrippedCommand {
    /// Each quoted literal replaced by [`LITERAL_MARK`]: for the syntax checks, which must not
    /// look inside a literal (`'$(id)'` is inert).
    marked: Vec<char>,
    /// Each quoted literal replaced by its content, with whitespace and `; & | ( )` in it
    /// mapped to `_`: for the word-level checks, which must see the word the shell runs —
    /// `'ssh'`, `s'sh'` and `e''val` are `ssh` and `eval`, while `'a;ssh;b'` stays the one
    /// harmless word `a_ssh_b`.
    words: Vec<char>,
    /// For each char of [`Self::words`], the index of the char it came from in the text that
    /// was stripped (a literal's content chars map to their own position inside the quotes).
    words_origin: Vec<usize>,
}

/// Checks the quoted literals in `residual`, or says why one is unsafe.
///
/// A quoted string is allowed next to substituted placeholders only when it is a closed
/// literal that every shell reads the same way and that contains no placeholder — exactly the
/// two forms [`portable_shell_word`] itself writes, which generated commands bake in (the base
/// branch of `git worktree add`): `'...'` without a backslash or typographic single quote, and
/// `"..."` without `$`, `` ` ``, `\`, `!` or a typographic double quote. With every quote
/// pair such a literal, no substituted word can sit inside quotes in any shell. Anything else
/// — an unclosed quote, a placeholder or line break inside quotes, a typographic quote outside
/// one — is refused.
fn strip_literal_quoted_strings(residual: &[char]) -> Result<StrippedCommand, &'static str> {
    let mut marked = Vec::with_capacity(residual.len());
    let mut words = Vec::with_capacity(residual.len());
    let mut words_origin = Vec::with_capacity(residual.len());
    let mut index = 0;
    while index < residual.len() {
        let c = residual[index];
        let forbidden_inside: &[char] = match c {
            '\'' => &['\\', '\u{2018}', '\u{2019}', '\u{201A}', '\u{201B}'],
            '"' => &['$', '`', '\\', '!', '\u{201C}', '\u{201D}', '\u{201E}'],
            c if QUOTE_CHARS.contains(&c) => return Err("a typographic quote"),
            c => {
                marked.push(c);
                words.push(c);
                words_origin.push(index);
                index += 1;
                continue;
            }
        };
        let Some(length) = residual[index + 1..].iter().position(|&next| next == c) else {
            return Err("an unclosed quote");
        };
        let content = &residual[index + 1..index + 1 + length];
        if content.contains(&PLACEHOLDER_MARK) {
            return Err("a placeholder inside quotes");
        }
        if content
            .iter()
            .any(|&inner| inner == '\n' || inner == '\r' || forbidden_inside.contains(&inner))
        {
            return Err("quotes whose content the shells read differently");
        }
        marked.push(LITERAL_MARK);
        words.extend(content.iter().map(|&inner| {
            if inner.is_whitespace() || matches!(inner, ';' | '&' | '|' | '(' | ')') {
                '_'
            } else {
                inner
            }
        }));
        words_origin.extend(index + 1..index + 1 + length);
        index += length + 2;
    }
    Ok(StrippedCommand {
        marked,
        words,
        words_origin,
    })
}

/// Shell syntax that a command with a substituted placeholder must not contain anywhere: a
/// substituted word is quoted for "an ordinary argument word", and each of these opens a
/// context where that quoting no longer means what it says (#878). `residual` is the
/// [`StrippedCommand::marked`] form.
fn forbidden_syntax_around_placeholders(residual: &[char]) -> Option<&'static str> {
    let text: String = residual.iter().collect();
    for (needle, what) in [
        ("$(", "`$(...)`"),
        ("${", "`${...}`"),
        ("$[", "`$[...]` arithmetic"),
        ("(e:", "a zsh `(e:...)` glob qualifier"),
        ("((", "`((...))`"),
        ("<<", "a heredoc"),
        ("--%", "PowerShell's `--%` stop-parsing token"),
    ] {
        if text.contains(needle) {
            return Some(what);
        }
    }
    let mut bracket_depth = 0usize;
    for (index, &c) in residual.iter().enumerate() {
        let what = match c {
            '\n' | '\r' => "a line break",
            '`' => "a backtick",
            '\\' => "a backslash",
            c if QUOTE_CHARS.contains(&c) => "quotes",
            '#' if index == 0
                || residual[index - 1].is_whitespace()
                || matches!(residual[index - 1], ';' | '&' | '|' | '(' | ')' | '<' | '>') =>
            {
                "a comment"
            }
            '[' => {
                bracket_depth += 1;
                continue;
            }
            ']' => {
                bracket_depth = bracket_depth.saturating_sub(1);
                continue;
            }
            // Inside `[...]` — a subscript, `[ ... ]`/`[[ ... ]]` test or glob class — a
            // word may be evaluated as arithmetic or a pattern.
            PLACEHOLDER_MARK if bracket_depth > 0 => "a placeholder inside `[...]`",
            _ => continue,
        };
        return Some(what);
    }
    None
}

