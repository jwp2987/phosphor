/// How a precommand's own options are laid out: the short options and long options that
/// take a value (`timeout -s KILL`, `sudo -u me`), and how many positional words come before
/// the command it runs (`timeout DURATION`, `flock FILE`).
struct PrecommandOptions {
    short_with_value: &'static str,
    long_with_value: &'static [&'static str],
    positional: usize,
}

fn precommand_options(command: &str) -> PrecommandOptions {
    let (short_with_value, long_with_value, positional): (&str, &[&str], usize) = match command {
        "timeout" => ("sk", &["signal", "kill-after"], 1),
        "nice" => ("n", &["adjustment"], 0),
        "sudo" => (
            "ugCDhprtUTR",
            &[
                "user",
                "group",
                "close-from",
                "chdir",
                "host",
                "prompt",
                "role",
                "type",
                "other-user",
                "command-timeout",
                "chroot",
            ],
            0,
        ),
        "doas" => ("uC", &[], 0),
        "env" => ("uC", &["unset", "chdir"], 0),
        "exec" => ("a", &[], 0),
        "ionice" => ("cnp", &["class", "classdata", "pid"], 0),
        "stdbuf" => ("ioe", &["input", "output", "error"], 0),
        "flock" => ("wE", &["wait", "timeout", "conflict-exit-code"], 1),
        "time" => ("fo", &["format", "output"], 0),
        "chrt" | "taskset" => ("", &[], 1),
        _ => ("", &[], 0),
    };
    PrecommandOptions {
        short_with_value,
        long_with_value,
        positional,
    }
}

/// The letters of a short-option cluster (`-iS` → `iS`, `-c{{x}}` → `c`); empty for anything
/// else.
fn short_option_letters(word: &str) -> &str {
    match word.strip_prefix('-') {
        Some(rest) if !rest.starts_with('-') => {
            let end = rest
                .find(|c: char| !c.is_ascii_alphabetic())
                .unwrap_or(rest.len());
            &rest[..end]
        }
        _ => "",
    }
}

/// Whether `word` is `long` or a getopt abbreviation of it at least `minimum` characters long,
/// with or without `=value` (`--sp`, `--split-string=x`).
fn is_long_option(word: &str, long: &str, minimum: usize) -> bool {
    let flag = word.split_once('=').map_or(word, |(flag, _)| flag);
    flag.starts_with("--") && flag.len() >= minimum && long.starts_with(flag)
}

/// A precommand option that makes it run a shell or split a string into a command: `env -S`,
/// `sudo -s`/`-i`, `doas -s`, `flock -c`. Matched inside short-option clusters (`env -iS`,
/// `sudo -Es`, `flock -xc`) and as long options or their abbreviations.
fn is_shell_running_option(command: &str, word: &str) -> bool {
    let letters = short_option_letters(word);
    match command {
        "env" => letters.contains('S') || is_long_option(word, "--split-string", 3),
        "sudo" => {
            letters.contains(|c: char| c == 's' || c == 'i')
                || is_long_option(word, "--shell", 4)
                || is_long_option(word, "--login", 3)
        }
        "doas" => letters.contains('s'),
        "flock" => letters.contains('c') || is_long_option(word, "--command", 4),
        _ => false,
    }
}

/// `test`/`[`/`[[` operators whose operands are arithmetic or variable names.
const TEST_OPERATORS: [&str; 10] = [
    "-eq", "-ne", "-lt", "-le", "-gt", "-ge", "-v", "-nt", "-ot", "-ef",
];

/// A command word made only of these characters cannot be a brace expansion, glob, variable
/// or quoting trick: `^[A-Za-z0-9_./:-]+$`, plus the test commands `[` and `[[`.
fn is_plain_command_word(word: &str) -> bool {
    matches!(word, "[" | "[[")
        || (!word.is_empty()
            && word
                .chars()
                .all(|c| c.is_ascii_alphanumeric() || matches!(c, '_' | '.' | '/' | ':' | '-')))
}

/// `NAME=value` or `NAME+=value`.
fn is_assignment(word: &str) -> bool {
    word.split_once('=').is_some_and(|(name, _)| {
        let name = name.strip_suffix('+').unwrap_or(name);
        name.starts_with(|c: char| c.is_ascii_alphabetic() || c == '_')
            && name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')
    })
}

/// For a redirection token (`>file`, `2>`, `&>`, `<`, `>>x`, ...), whether its target is the
/// next word; `None` when `word` is not a redirection.
fn redirection_takes_next_word(word: &str) -> Option<bool> {
    let operator = word.trim_start_matches(|c: char| c.is_ascii_digit());
    if !(operator.starts_with('<') || operator.starts_with('>') || operator.starts_with("&>")) {
        return None;
    }
    let target = operator.trim_start_matches(|c: char| matches!(c, '<' | '>' | '&' | '|'));
    Some(target.is_empty())
}

/// A command word by basename, lowercased, without `.exe`.
fn command_name(word: &str) -> String {
    let base = word
        .rsplit(|c: char| c == '/' || c == '\\')
        .next()
        .unwrap_or(word)
        .to_ascii_lowercase();
    base.strip_suffix(".exe")
        .map(str::to_string)
        .unwrap_or(base)
}

/// Whether `name` (a [`command_name`]) is denied, also without a trailing version
/// (`python3.14` → `python`, `perl5.40.1` → `perl`, `node-18` → `node`).
fn is_denied_command(name: &str) -> bool {
    let unversioned = name.trim_end_matches(|c: char| c.is_ascii_digit() || c == '.');
    let unversioned = if unversioned.len() < name.len() {
        unversioned.strip_suffix('-').unwrap_or(unversioned)
    } else {
        name
    };
    DENIED_COMMANDS.contains(&name)
        || (!unversioned.is_empty() && DENIED_COMMANDS.contains(&unversioned))
}

/// Why `word` may not be a command word, if it may not.
fn command_word_problem(word: &str) -> Option<&'static str> {
    if word.starts_with('$') {
        Some("a variable as the command name")
    } else if word.contains(PLACEHOLDER_MARK) {
        Some("a placeholder as the command name")
    } else if !is_plain_command_word(word) {
        Some("a command name that is not a plain word")
    } else if is_denied_command(&command_name(word)) {
        Some("a command that runs its input or arguments as code")
    } else if is_proc_exe(word) {
        // `/proc/self/exe` is whatever program is running, typically the shell itself.
        Some("a /proc/.../exe path as the command name")
    } else {
        None
    }
}

/// `/proc/self/exe`, `/proc/<pid>/exe` and `/proc/thread-self/exe`.
fn is_proc_exe(word: &str) -> bool {
    word.strip_prefix("/proc/")
        .is_some_and(|rest| rest.ends_with("/exe") && !rest.contains("//"))
}

/// Checks the whole segment, whatever its command word is, for a placeholder as the value of a
/// variable that is evaluated later (#884). Only segments that contain a placeholder are
/// checked.
fn segment_evaluates_placeholder(words: &[&str]) -> Option<&'static str> {
    if !words.iter().any(|word| word.contains(PLACEHOLDER_MARK)) {
        return None;
    }
    for (at, &word) in words.iter().enumerate() {
        if is_assignment(word)
            && let Some((name, value)) = word.split_once('=')
            && value.contains(PLACEHOLDER_MARK)
            && EVALUATED_VARIABLES.contains(&name.trim_end_matches('+'))
        {
            return Some("a placeholder as the value of a variable the shell evaluates later");
        }
        // fish: `set -gx PS1 {{x}}`. Only after `set` and its options: a bare word that
        // happens to be a variable's name (`echo PS1 {{x}}`) is just an argument.
        let after_set = words[..at]
            .iter()
            .rev()
            .find(|earlier| !earlier.starts_with('-'))
            .is_some_and(|earlier| matches!(*earlier, "set" | "setenv"));
        if after_set
            && EVALUATED_VARIABLES.contains(&word)
            && words
                .get(at + 1)
                .is_some_and(|next| next.contains(PLACEHOLDER_MARK))
        {
            return Some("a placeholder as the value of a variable the shell evaluates later");
        }
    }
    None
}

/// Checks the command word of every segment of a command that substitutes a placeholder.
///
/// Best-effort and structural, not a shell parser. The command is split into segments at
/// `; & | ( )` and at standalone `{`/`}` words. In each, leading keywords (`if`, `!`,
/// `coproc`, fish `and`/`not`, ...), redirections and `VAR=value` assignments are skipped and
/// the next word is the command word. It is refused when it starts with `$`, contains a
/// placeholder, is not a plain word (see [`is_plain_command_word`]: no brace expansion or
/// glob can make it another command), or is in [`DENIED_COMMANDS`] (also with a version
/// suffix). A precommand ([`PRECOMMANDS`]: `sudo`, `env`, `time`, `timeout`, `nohup`, ...)
/// has its own options skipped — with their values, per [`precommand_options`] — and its
/// positional words (`timeout DURATION`, `flock FILE`), and the word after them is checked as
/// a command word in turn. Options that make a precommand run a shell are refused
/// ([`is_shell_running_option`]), including when a placeholder is attached (`env -S{{x}}`);
/// `flock` permutes its arguments, so all its words are checked for `-c`. A few commands are
/// refused only with the arguments that make them evaluate code: `docker`/`podman`/`nerdctl` `run` with a placeholder outside the image argument, `kubectl
/// exec`, `find -exec`, `script -c` (in any short-option cluster) or `--command`, `git -c
/// alias.*` or a `git -c` whose value is a placeholder, `test`/`[`/`[[` with an arithmetic or
/// name operator, `printf`/`print` with `-v` or a numeric conversion, `export -i`, `wait -p`
/// and `set -A`.
///
/// `residual` is the [`StrippedCommand::words`] form, so a quoted command name is seen
/// unquoted. Wrappers that run another command but are not precommands (`strace`,
/// `dbus-run-session`, `unshare`, ...) are in [`DENIED_COMMANDS`]; a segment with a placeholder
/// is also refused when the placeholder is the value of a variable evaluated later
/// ([`EVALUATED_VARIABLES`]: `PS1`, `PROMPT_COMMAND`, `GIT_SSH_COMMAND`, `EDITOR`, ...; #884).
/// Aliases, functions and scripts defined elsewhere are invisible here; placeholders are
/// supported only as ordinary arguments to ordinary commands.
fn reparsing_command(residual: &[char]) -> Option<&'static str> {
    let text: String = residual
        .iter()
        .map(|&c| {
            if matches!(c, ';' | '&' | '|' | '(' | ')') {
                '\n'
            } else {
                c
            }
        })
        .collect();
    let mut segments: Vec<Vec<&str>> = Vec::new();
    for line in text.lines() {
        let mut current = Vec::new();
        for word in line.split_whitespace() {
            if matches!(word, "{" | "}") {
                if !current.is_empty() {
                    segments.push(std::mem::take(&mut current));
                }
            } else {
                current.push(word);
            }
        }
        if !current.is_empty() {
            segments.push(current);
        }
    }

    for words in segments {
        if let Some(problem) = segment_evaluates_placeholder(&words) {
            return Some(problem);
        }
        let mut index = 0;
        while let Some(&word) = words.get(index) {
            if LEADING_KEYWORDS.contains(&word) || is_assignment(word) {
                index += 1;
            } else if let Some(takes_next) = redirection_takes_next_word(word) {
                index += if takes_next { 2 } else { 1 };
            } else {
                break;
            }
        }

        while let Some(&command_word) = words.get(index) {
            if let Some(problem) = command_word_problem(command_word) {
                return Some(problem);
            }
            let command = command_name(command_word);
            if !PRECOMMANDS.contains(&command.as_str()) {
                if arguments_evaluate_code(&command, &words[index + 1..]) {
                    return Some("arguments that make the command evaluate code or arithmetic");
                }
                break;
            }

            // A precommand: skip its options (refusing the shell-running ones) and
            // positional words; the next word is the command it runs.
            if command == "flock"
                && words[index + 1..]
                    .iter()
                    .any(|word| is_shell_running_option(&command, word))
            {
                return Some("a precommand option that runs a shell");
            }
            let options = precommand_options(&command);
            index += 1;
            while let Some(&option) = words.get(index) {
                if !option.starts_with('-') || option == "-" {
                    break;
                }
                if is_shell_running_option(&command, option) {
                    return Some("a precommand option that runs a shell");
                }
                if option == "--" {
                    index += 1;
                    break;
                }
                let takes_value = if let Some(long) = option.strip_prefix("--") {
                    !long.contains('=') && options.long_with_value.contains(&long)
                } else {
                    let letters = short_option_letters(option);
                    // The value is the next word only when the value-taking letter ends the
                    // word (`-n 5`); `-n5` carries it attached.
                    letters
                        .char_indices()
                        .find(|(_, letter)| options.short_with_value.contains(*letter))
                        .is_some_and(|(at, _)| at + 1 == option.len() - 1)
                };
                index += if takes_value { 2 } else { 1 };
            }
            while words.get(index).is_some_and(|word| is_assignment(word)) {
                index += 1;
            }
            index += options.positional;
        }
    }
    None
}

/// Arguments that make an ordinary command evaluate code, arithmetic or a variable name.
fn arguments_evaluate_code(command: &str, rest: &[&str]) -> bool {
    let has = |flag: &str| rest.iter().any(|word| *word == flag);
    match command {
        "docker" | "podman" | "nerdctl" => has("exec") || container_run_evaluates_placeholder(rest),
        "kubectl" => has("exec") || kubectl_run_evaluates_placeholder(rest),
        "find" => ["-exec", "-execdir", "-ok", "-okdir"]
            .iter()
            .any(|flag| has(*flag)),
        "script" => rest.iter().any(|word| {
            short_option_letters(word).contains('c') || is_long_option(word, "--command", 4)
        }),
        "git" => {
            rest.iter().any(|word| word.starts_with("alias."))
                || rest
                    .windows(2)
                    .any(|pair| pair[0] == "-c" && pair[1].contains(PLACEHOLDER_MARK))
        }
        "test" | "[" | "[[" => TEST_OPERATORS.iter().any(|flag| has(*flag)),
        "printf" | "print" => has("-v") || rest.iter().any(|word| has_numeric_conversion(word)),
        "export" => rest
            .iter()
            .any(|word| word.starts_with('-') && word.contains('i')),
        "wait" => has("-p"),
        "set" => has("-A") || has("+A"),
        _ => false,
    }
}

/// How `docker run`-style options consume the next word.
enum RunOption {
    /// A boolean flag: takes no value.
    Flag,
    /// Takes a value: the next word, or the rest of the word when attached.
    Value,
    /// Not known: the next word may or may not be its value.
    Unknown,
}

/// Classifies a `docker`/`podman`/`nerdctl run` option word (starting with `-`).
fn container_run_option_kind(option: &str) -> RunOption {
    const FLAG_LONG: &[&str] = &[
        "rm",
        "privileged",
        "detach",
        "interactive",
        "tty",
        "publish-all",
        "init",
        "read-only",
        "sig-proxy",
        "oom-kill-disable",
        "no-healthcheck",
        "disable-content-trust",
        "quiet",
        "help",
    ];
    const VALUE_LONG: &[&str] = &[
        "name",
        "user",
        "workdir",
        "env",
        "env-file",
        "volume",
        "publish",
        "network",
        "mount",
        "entrypoint",
        "hostname",
        "memory",
        "cpus",
        "label",
        "add-host",
        "cap-add",
        "cap-drop",
        "device",
        "dns",
        "expose",
        "group-add",
        "ipc",
        "pid",
        "platform",
        "pull",
        "restart",
        "security-opt",
        "shm-size",
        "tmpfs",
        "ulimit",
        "uts",
        "volumes-from",
        "cidfile",
        "link",
        "log-driver",
        "log-opt",
        "mac-address",
        "runtime",
        "stop-signal",
        "stop-timeout",
        "userns",
        "annotation",
        "cgroupns",
    ];
    if let Some(long) = option.strip_prefix("--") {
        if long.contains('=') || FLAG_LONG.contains(&long) {
            RunOption::Flag
        } else if VALUE_LONG.contains(&long) {
            RunOption::Value
        } else {
            RunOption::Unknown
        }
    } else {
        let letters = short_option_letters(option);
        for (at, letter) in letters.char_indices() {
            if "ditPq".contains(letter) {
                continue;
            }
            if "evpwulmcah".contains(letter) {
                // The value is the next word only when the letter ends the whole word
                // (`-p 80`); `-p80` carries it attached.
                return if at + 1 == letters.len() && letters.len() + 1 == option.len() {
                    RunOption::Value
                } else {
                    RunOption::Flag
                };
            }
            return RunOption::Unknown;
        }
        RunOption::Flag
    }
}

/// Whether a `docker`/`podman`/`nerdctl run` segment puts a placeholder anywhere but the image
/// argument (#884). The image is a name the container runtime pulls, not code; options
/// (mounts, `--privileged`, `--entrypoint`, environment) and everything after the image (the
/// command the container runs) are refused. A segment with no placeholder is not restricted.
fn container_run_evaluates_placeholder(rest: &[&str]) -> bool {
    let marked = |word: &str| word.contains(PLACEHOLDER_MARK);
    let Some(run) = rest.iter().position(|word| *word == "run") else {
        return false;
    };
    if rest[..run].iter().any(|word| marked(word)) {
        return true;
    }
    let args = &rest[run + 1..];
    let mut index = 0;
    while let Some(&word) = args.get(index) {
        if word == "--" {
            index += 1;
            break;
        }
        if !word.starts_with('-') || word == "-" {
            break;
        }
        if marked(word) {
            return true;
        }
        match container_run_option_kind(word) {
            RunOption::Flag => index += 1,
            RunOption::Value => {
                if args.get(index + 1).is_some_and(|value| marked(value)) {
                    return true;
                }
                index += 2;
            }
            // Cannot tell whether the next word is the image: refuse any placeholder.
            RunOption::Unknown => return args.iter().any(|word| marked(word)),
        }
    }
    // `args[index]` is the image; whatever follows is the container's command.
    args.get(index + 1..)
        .is_some_and(|after| after.iter().any(|word| marked(word)))
}

/// Whether a `kubectl run` segment puts a placeholder anywhere but the value of `--image`.
fn kubectl_run_evaluates_placeholder(rest: &[&str]) -> bool {
    let marked = |word: &str| word.contains(PLACEHOLDER_MARK);
    let Some(run) = rest.iter().position(|word| *word == "run") else {
        return false;
    };
    if rest[..run].iter().any(|word| marked(word)) {
        return true;
    }
    let args = &rest[run + 1..];
    let mut after_separator = false;
    for (index, &word) in args.iter().enumerate() {
        if word == "--" {
            after_separator = true;
        }
        if !marked(word) {
            continue;
        }
        let is_image = !after_separator
            && (word
                .strip_prefix("--image=")
                .is_some_and(|value| marked(value))
                || (index > 0 && args[index - 1] == "--image"));
        if !is_image {
            return true;
        }
    }
    false
}

fn has_numeric_conversion(word: &str) -> bool {
    let mut chars = word.chars().peekable();
    while let Some(c) = chars.next() {
        if c != '%' {
            continue;
        }
        while chars.peek().is_some_and(|&next| {
            matches!(next, '-' | '+' | ' ' | '#' | '.') || next.is_ascii_digit()
        }) {
            chars.next();
        }
        if chars
            .next()
            .is_some_and(|conversion| "diouxXeEfFgGaAc".contains(conversion))
        {
            return true;
        }
    }
    false
}

/// Renders one command template, substituting each referenced value as a single shell word
/// spelled by [`portable_shell_word`]. Placeholders without a value are left as they are.
///
/// The word's quoting is only right where a shell reads an ordinary argument word, and this
/// does not parse shell to find out where that is. Instead a command with any substituted
/// placeholder is held to a conservative whitelist (#878): a placeholder written as exactly
/// `"{{x}}"` or `'{{x}}'` has that quote pair dropped; any other quoted string must be a closed
/// literal with no placeholder inside (see [`strip_literal_quoted_strings`] — the form
/// generated commands bake the base branch in); outside those literals the command must
/// contain no `$(`, `${`, `$[`, `((`, `<<`, `(e:`, backtick, backslash, line break or
/// word-initial `#`, no `$` or `[` directly before a placeholder or placeholder inside
/// `[...]`, and every segment's command word must pass the structural check in
/// [`reparsing_command`] (a plain word, not a shell, interpreter, evaluator or
/// arithmetic/name builtin, no evaluating flags). This is best-effort, not a shell parser:
/// placeholders are supported only as ordinary arguments to ordinary commands. Anything else
/// is an
/// error naming the placeholders: quotes around or near the placeholder, command
/// substitution, parameter expansion, arithmetic, heredocs and comments all change what the
/// substituted quoting means, and the shells disagree on them. A value with no portable
/// spelling is an error too. Commands without substituted placeholders are not restricted.
pub(crate) fn render_command(
    template: &str,
    values: &HashMap<String, String>,
) -> Result<String, String> {
    use handlebars::parser::{ParsedArgumentResult, ParsedArgumentsIterator};

    let chars: Vec<char> = template.chars().collect();
    // (start, end, word, description): the chars `start..end` — the placeholder and any
    // exact wrapping quote pair — are replaced by `word`.
    let mut spans: Vec<(usize, usize, String, String)> = Vec::new();
    for parsed in ParsedArgumentsIterator::new(template.chars()) {
        if !matches!(parsed.result(), ParsedArgumentResult::Valid { .. }) {
            continue;
        }
        let name_range = parsed.chars_range();
        // Same guard as `handlebars::render_template`: a valid argument has two braces each side.
        if name_range.start < 2 {
            continue;
        }
        let name: String = chars[name_range.clone()].iter().collect();
        let Some(value) = values.get(&name) else {
            continue;
        };
        let word = portable_shell_word(value).ok_or_else(|| {
            format!(
                "the value of `{name}` ({value:?}) has no quoting that every supported shell \
                 reads the same way"
            )
        })?;

        let (mut start, mut end) = (name_range.start - 2, name_range.end + 2);
        let previous_end = spans.last().map_or(0, |span| span.1);
        if start > previous_end
            && matches!(chars[start - 1], '\'' | '"')
            && chars.get(end) == Some(&chars[start - 1])
        {
            start -= 1;
            end += 1;
        }
        // After `$`, bash/zsh read a quoted word as `$'...'`/`$"..."` and fish rejects it;
        // after `[` it is an array subscript (`arr[...]`, zsh `h[...]`), evaluated as
        // arithmetic or a pattern.
        if start > 0 && matches!(chars[start - 1], '$' | '[') {
            return Err(format!(
                "`{{{{{name}}}}}` directly follows `{}` in the command {template:?}, so its \
                 value ({value:?}) cannot be quoted safely",
                chars[start - 1]
            ));
        }
        spans.push((
            start,
            end,
            word.into_owned(),
            format!("`{{{{{name}}}}}` ({value:?})"),
        ));
    }
    if spans.is_empty() {
        return Ok(template.to_string());
    }

    // The command with every substituted span replaced by `PLACEHOLDER_MARK`.
    let mut residual = Vec::with_capacity(chars.len());
    let mut cursor = 0;
    for (start, end, _, _) in &spans {
        residual.extend_from_slice(&chars[cursor..*start]);
        residual.push(PLACEHOLDER_MARK);
        cursor = *end;
    }
    residual.extend_from_slice(&chars[cursor..]);
    let checked = strip_literal_quoted_strings(&residual).and_then(|stripped| {
        match forbidden_syntax_around_placeholders(&stripped.marked)
            .or_else(|| reparsing_command(&stripped.words))
        {
            Some(what) => Err(what),
            None => Ok(()),
        }
    });
    if let Err(what) = checked {
        let names = spans
            .iter()
            .map(|(_, _, _, description)| description.as_str())
            .collect::<Vec<_>>()
            .join(", ");
        return Err(format!(
            "the command {template:?} substitutes {names} but also contains {what}, which a \
             substituted value cannot be quoted safely around; use each placeholder as a plain \
             word outside any quotes (`cd {{{{name}}}}`), with no `$(...)`, `${{...}}`, \
             backticks, backslashes, heredocs, comments or line breaks in the same command"
        ));
    }

    let mut out = String::with_capacity(template.len());
    let mut cursor = 0;
    for (start, end, word, _) in &spans {
        out.extend(&chars[cursor..*start]);
        out.push_str(word);
        cursor = *end;
    }
    out.extend(&chars[cursor..]);
    Ok(out)
}

// ── Flat pane tree resolution ───────────────────────────────────────

/// Builds a [`PaneTemplateType`] tree from a flat `[[panes]]` list.
///
/// The first entry is the root.  Split nodes reference children by ID;
/// leaf nodes produce terminal panes.
fn resolve_pane_tree(
    panes: &[TabConfigPaneNode],
    context: &HashMap<String, String>,
) -> Result<PaneTemplateType, ResolveError> {
    if panes.is_empty() {
        return Err("panes array is empty".to_string().into());
    }

    let pane_map: HashMap<&str, &TabConfigPaneNode> =
        panes.iter().map(|p| (p.id.as_str(), p)).collect();

    if pane_map.len() != panes.len() {
        return Err("duplicate pane IDs detected".to_string().into());
    }

    let root = &panes[0];
    let has_explicit_focus = panes
        .iter()
        .any(|p| p.split.is_none() && p.is_focused == Some(true));

    let (template, _) = resolve_pane_node(
        root,
        &pane_map,
        context,
        !has_explicit_focus, // auto-focus first leaf when nothing is explicitly focused
    )?;

    Ok(template)
}

/// Recursively resolves a single pane node.
///
/// Returns `(PaneTemplateType, did_consume_auto_focus)` — the second element
/// is `true` when a leaf consumed the auto-focus so subsequent leaves are not
/// also focused.
fn resolve_pane_node(
    node: &TabConfigPaneNode,
    pane_map: &HashMap<&str, &TabConfigPaneNode>,
    context: &HashMap<String, String>,
    auto_focus_first_leaf: bool,
) -> Result<(PaneTemplateType, bool), ResolveError> {
    if let Some(split_direction) = &node.split {
        // ── Split node ──────────────────────────────────────────────
        let children = node
            .children
            .as_ref()
            .ok_or_else(|| format!("split node '{}' is missing 'children'", node.id))?;

        if children.len() < 2 {
            return Err(format!(
                "split node '{}' must have at least 2 children, got {}",
                node.id,
                children.len()
            )
            .into());
        }

        let mut child_templates = Vec::with_capacity(children.len());
        let mut auto_focus_remaining = auto_focus_first_leaf;

        for child_id in children {
            let child = pane_map.get(child_id.as_str()).ok_or_else(|| {
                format!(
                    "split node '{}' references unknown child '{}'",
                    node.id, child_id
                )
            })?;
            let (child_template, did_focus) =
                resolve_pane_node(child, pane_map, context, auto_focus_remaining)?;
            if did_focus {
                auto_focus_remaining = false;
            }
            child_templates.push(child_template);
        }

        Ok((
            PaneTemplateType::PaneBranchTemplate {
                split_direction: split_direction.clone(),
                panes: child_templates,
            },
            auto_focus_first_leaf && !auto_focus_remaining,
        ))
    } else {
        // ── Leaf node ────────────────────────────────────────────────
        let pane_type = node
            .pane_type
            .as_ref()
            .ok_or_else(|| format!("leaf pane '{}' is missing required 'type' field", node.id))?;

        let pane_mode = match pane_type {
            TabConfigPaneType::Terminal => PaneMode::Terminal,
            TabConfigPaneType::Agent => PaneMode::Agent,
        };

        let directory = node
            .directory
            .as_deref()
            .map(|c| handlebars::render_template(c, context));
        let cwd = directory
            .as_deref()
            .map(|rendered| PathBuf::from(shellexpand::tilde(rendered).into_owned()))
            .unwrap_or_default();

        let command_values = command_values_for_pane(context, directory.as_deref());
        let commands: Vec<CommandTemplate> = node
            .commands
            .as_deref()
            .unwrap_or_default()
            .iter()
            .map(|cmd| {
                upgrade_legacy_worktree_path(cmd, directory.as_deref())
                    .and_then(|cmd| render_command(&cmd, &command_values))
                    .map(|exec| CommandTemplate { exec })
                    .map_err(|err| {
                        ResolveError::UnsafeCommand(format!("pane '{}': {err}", node.id))
                    })
            })
            .collect::<Result<_, _>>()?;

        let explicitly_focused = node.is_focused == Some(true);
        let is_focused = explicitly_focused || auto_focus_first_leaf;
        let did_consume = is_focused && !explicitly_focused;

        Ok((
            PaneTemplateType::PaneTemplate {
                cwd,
                commands,
                is_focused: Some(is_focused),
                pane_mode,
                shell: node.shell.clone(),
            },
            explicitly_focused || did_consume,
        ))
    }
}

/// Builds a worktree tab config TOML string.
///
/// When `worktree_branch_name` is `Some(name)` (manual naming), the returned
/// TOML bakes commands with Handlebars template variables and exposes a
/// `worktree_branch_name` param so re-opens show the params modal.
///
/// When `None` (autogenerate), the TOML stores commands with
/// `{{autogenerated_branch_name}}` Handlebars template variables that get
/// substituted with a fresh name on every open.
///
/// Nothing derived from the repository is written into the command text: the worktree path
/// (which contains the repo directory's name) is the render-time `{{worktree_path}}` and is
/// quoted when the config is opened. The base branch is the one value baked in, as a single
/// [`portable_shell_word`] after `--`; a branch name with no portable spelling, or one that
/// contains a `{{`/`}}` the later render would substitute into, is refused (#878).
#[cfg(feature = "local_fs")]
pub(crate) fn build_worktree_config_toml(
    config_name: &str,
    repo: &str,
    base_branch: &str,
    worktree_branch_name: Option<&str>,
) -> Result<String, String> {
    let mut doc = toml::map::Map::new();
    doc.insert("name".into(), Value::String(config_name.to_string()));

    let mut pane = toml::map::Map::new();
    pane.insert("id".into(), Value::String("main".into()));
    pane.insert("type".into(), Value::String("terminal".into()));
    pane.insert("directory".into(), Value::String(repo.to_string()));

    let branch_var = if worktree_branch_name.is_some() {
        WORKTREE_BRANCH_NAME_PARAM
    } else {
        AUTOGENERATED_BRANCH_NAME_PARAM
    };
    let commands = worktree_setup_commands(branch_var, Some(base_branch))?;
    pane.insert(
        "commands".into(),
        Value::Array(commands.into_iter().map(Value::String).collect()),
    );
    doc.insert("panes".into(), Value::Array(vec![Value::Table(pane)]));

    if worktree_branch_name.is_some() {
        doc.insert(
            "title".into(),
            Value::String(handlebars_placeholder(WORKTREE_BRANCH_NAME_PARAM)),
        );
        let mut param = toml::map::Map::new();
        param.insert("type".into(), Value::String("text".into()));
        param.insert(
            "description".into(),
            Value::String("Worktree branch name".to_string()),
        );
        let mut params = toml::map::Map::new();
        params.insert(WORKTREE_BRANCH_NAME_PARAM.into(), Value::Table(param));
        doc.insert("params".into(), Value::Table(params));
    }

    Ok(toml::to_string_pretty(&Value::Table(doc)).expect("generated TOML should always serialize"))
}

/// The commands that create a worktree for the branch held in `branch_var` and enter it:
/// `git worktree add -b {{branch_var}} -- {{worktree_path}} [<base>]` and
/// `cd {{worktree_path}}`.
///
/// `--` ends git's option parsing, so a base branch (or, defensively, a path) that starts
/// with `-` is a positional argument; `-b` always takes the next word as its value. An empty
/// `base_branch` is omitted, leaving git to use `HEAD`.
pub(crate) fn worktree_setup_commands(
    branch_var: &str,
    base_branch: Option<&str>,
) -> Result<Vec<String>, String> {
    let branch = handlebars_placeholder(branch_var);
    let worktree_path = handlebars_placeholder(WORKTREE_PATH_VAR);
    let mut add = format!("git worktree add -b {branch} -- {worktree_path}");
    if let Some(base_branch) = base_branch.filter(|base| !base.is_empty()) {
        if base_branch.contains("{{") || base_branch.contains("}}") {
            return Err(format!(
                "base branch {base_branch:?} contains a template brace pair; refusing to create \
                 the worktree config"
            ));
        }
        let word = portable_shell_word(base_branch).ok_or_else(|| {
            format!(
                "base branch {base_branch:?} has no quoting that every supported shell reads the \
                 same way; refusing to create the worktree config"
            )
        })?;
        add.push(' ');
        add.push_str(&word);
    }
    Ok(vec![add, format!("cd {worktree_path}")])
}

