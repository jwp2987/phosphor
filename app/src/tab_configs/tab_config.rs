/// The pane type declared on leaf nodes via `type = "..."` in TOML.
#[derive(Clone, Debug, Deserialize, Serialize, PartialEq, Eq)]
#[serde(rename_all = "snake_case")]
pub enum TabConfigPaneType {
    /// A standard terminal shell session.
    Terminal,
    /// A terminal that immediately enters Agent Mode.
    #[serde(alias = "cloud")]
    Agent,
}

/// A single node in the flat `[[panes]]` array.  Distinguished as a split vs.
/// leaf by the presence of `split` + `children`.
///
/// Leaf panes must specify `type` to indicate whether they open as a terminal
/// or agent pane. Legacy `cloud` entries deserialize as local agent panes.
#[derive(Clone, Debug, Deserialize, Serialize)]
#[serde(deny_unknown_fields)]
pub struct TabConfigPaneNode {
    pub id: String,

    /// The pane type. Required on leaf nodes; ignored on split nodes.
    #[serde(rename = "type")]
    pub pane_type: Option<TabConfigPaneType>,

    // -- Split fields (present for branches) --
    pub split: Option<SplitDirection>,
    pub children: Option<Vec<String>>,

    // -- Leaf fields --
    pub is_focused: Option<bool>,
    pub directory: Option<String>,
    pub commands: Option<Vec<String>>,
    /// Optional shell to use for this pane (e.g. `"pwsh"`, `"zsh"`, `"bash"`, `"fish"`).
    /// Only applies to `terminal` and `agent` pane types.
    /// If omitted or the shell is not found, the user's default shell is used.
    pub shell: Option<String>,
}

// ── TabConfig ───────────────────────────────────────────────────────

/// A tab config loaded from a `.toml` file in `~/.warp/tab_configs/`.
///
/// Pane layout is defined with a flat `[[panes]]` array where the first entry
/// is the root and splits reference children by ID.
#[derive(Clone, Debug, Deserialize, Serialize)]
#[serde(deny_unknown_fields)]
pub struct TabConfig {
    /// Display name shown in the + menu.
    pub name: String,
    /// Optional tab title template. Supports `{{ }}` template variables.
    #[serde(default)]
    pub title: Option<String>,
    /// Optional tab color.
    #[serde(default)]
    pub color: Option<AnsiColorIdentifier>,
    /// Flat pane list. The first entry is the root of the pane tree.
    #[serde(default)]
    pub panes: Vec<TabConfigPaneNode>,
    /// Named parameters that the user fills in before the tab opens.
    /// Keys are parameter names (used in `{{ }}` placeholders).
    #[serde(default)]
    pub params: HashMap<String, TabConfigParam>,
    /// The on-disk path this config was loaded from.
    /// Populated during parsing; not serialized into or from the TOML.
    #[serde(skip)]
    pub source_path: Option<PathBuf>,
}

impl TabConfig {
    /// Returns param values using defaults where available, and empty strings for
    /// params with no default.  This is the fallback used when no param-fill UI is shown.
    pub fn default_param_values(&self) -> HashMap<String, String> {
        self.params
            .iter()
            .map(|(name, param)| {
                let value = param.default.clone().unwrap_or_default();
                (name.clone(), value)
            })
            .collect()
    }

    pub(crate) fn is_worktree(&self) -> bool {
        self.panes.iter().any(|pane| {
            pane.commands.as_ref().is_some_and(|commands| {
                commands
                    .iter()
                    .any(|command| command.contains("git worktree"))
            })
        })
    }

    pub(crate) fn uses_autogenerated_branch_name(&self) -> bool {
        self.title
            .as_deref()
            .is_some_and(contains_autogenerated_branch_name)
            || self.panes.iter().any(|pane| {
                pane.directory
                    .as_deref()
                    .is_some_and(contains_autogenerated_branch_name)
                    || pane.commands.as_ref().is_some_and(|commands| {
                        commands
                            .iter()
                            .any(|command| contains_autogenerated_branch_name(command))
                    })
            })
    }
}

/// Renders a [`TabConfig`] with the given param values into a [`PaneTemplateType`]
/// and an optional rendered title.
///
/// - `title` and `directory` receive unquoted param values (quoting would break paths).
/// - `commands` receive each value as one shell word spelled by [`portable_shell_word`]. That
///   spelling is only safe where a shell reads an ordinary argument word, so a command with a
///   substituted placeholder must stay within a conservative whitelist — the placeholder bare
///   or exactly `"{{x}}"`/`'{{x}}'`, other quotes only as closed plain literals with no
///   placeholder inside, and no `$(`, `${`, `$[`, `((`, `<<`, backticks, backslashes, comments
///   or line breaks in that command — or it is refused (#878); see [`render_command`].
/// - `worktree_branch_name`: when `Some`, injected into the template context as the
///   special-cased `autogenerated_branch_name` var so commands can use
///   `{{autogenerated_branch_name}}`.
/// - Commands may also use `{{worktree_path}}`, the generated worktree path for the pane's
///   directory and the worktree branch; see [`WORKTREE_PATH_VAR`].
///
/// A config that cannot be rendered — a structural error, or a command that cannot be made
/// safe — falls back to a single empty terminal. Callers that can tell the user why should
/// use [`try_render_tab_config`] instead.
pub fn render_tab_config(
    config: &TabConfig,
    param_values: &HashMap<String, String>,
    worktree_branch_name: Option<&str>,
) -> (Option<String>, PaneTemplateType) {
    try_render_tab_config(config, param_values, worktree_branch_name).unwrap_or_else(|err| {
        log::warn!(
            "Not running the commands of tab config '{}': {err}",
            config.name
        );
        (None, fallback_pane_template())
    })
}

/// [`render_tab_config`], except that a command which cannot be rendered safely is returned
/// as an error — naming the value that could not be quoted — instead of silently becoming an
/// empty terminal, so the caller can show it (#878). Structural errors in the pane tree still
/// fall back to an empty terminal, as before.
pub fn try_render_tab_config(
    config: &TabConfig,
    param_values: &HashMap<String, String>,
    worktree_branch_name: Option<&str>,
) -> Result<(Option<String>, PaneTemplateType), String> {
    let context = build_template_context(param_values, worktree_branch_name);

    let rendered_title = config
        .title
        .as_deref()
        .map(|t| handlebars::render_template(t, &context));

    let pane_template = match resolve_pane_tree(&config.panes, &context) {
        Ok(template) => template,
        Err(ResolveError::UnsafeCommand(err)) => return Err(err),
        Err(ResolveError::Structure(err)) => {
            log::warn!("Failed to resolve pane tree for '{}': {err}", config.name);
            fallback_pane_template()
        }
    };

    Ok((rendered_title, pane_template))
}

fn fallback_pane_template() -> PaneTemplateType {
    PaneTemplateType::PaneTemplate {
        cwd: PathBuf::new(),
        commands: Vec::new(),
        is_focused: Some(true),
        pane_mode: PaneMode::Terminal,
        shell: None,
    }
}

/// Why a pane tree could not be resolved.
enum ResolveError {
    /// The `[[panes]]` layout is malformed.
    Structure(String),
    /// A command could not be rendered without risking shell injection (#878).
    UnsafeCommand(String),
}

impl From<String> for ResolveError {
    fn from(err: String) -> Self {
        Self::Structure(err)
    }
}

/// The raw (unquoted) template values: the params plus the autogenerated branch name.
fn build_template_context(
    param_values: &HashMap<String, String>,
    worktree_branch_name: Option<&str>,
) -> HashMap<String, String> {
    let mut context = param_values.clone();
    if let Some(name) = worktree_branch_name {
        context.insert(
            AUTOGENERATED_BRANCH_NAME_PARAM.to_string(),
            name.to_string(),
        );
    }
    context
}

/// Adds [`WORKTREE_PATH_VAR`] for a pane whose directory is `directory`, unless a param of
/// that name already supplies it. The branch is the autogenerated name when there is one,
/// otherwise the `worktree_branch_name` param.
fn command_values_for_pane<'a>(
    context: &'a HashMap<String, String>,
    directory: Option<&str>,
) -> Cow<'a, HashMap<String, String>> {
    if context.contains_key(WORKTREE_PATH_VAR) {
        return Cow::Borrowed(context);
    }
    let branch = context
        .get(AUTOGENERATED_BRANCH_NAME_PARAM)
        .or_else(|| context.get(WORKTREE_BRANCH_NAME_PARAM));
    let (Some(directory), Some(branch)) = (directory, branch) else {
        return Cow::Borrowed(context);
    };
    let mut values = context.clone();
    values.insert(
        WORKTREE_PATH_VAR.to_string(),
        generated_worktree_path_string(Path::new(directory), branch),
    );
    Cow::Owned(values)
}

/// Rewrites the worktree path that configs generated before #878 baked into their commands —
/// `"<data dir>/worktrees/<repo name>/{{branch var}}"`, inside double quotes, where a repo
/// name containing `$(...)`, a backtick or `"` was shell syntax — to [`WORKTREE_PATH_VAR`],
/// so reopening such a saved config quotes the path instead of re-running the injection.
/// Only the exact strings those generators produced for this pane's directory are touched;
/// a legacy path under any other directory still has its placeholder inside double quotes,
/// which [`render_command`] refuses.
///
/// Those generators also appended the base branch unquoted. When the rewritten command is
/// the legacy `git worktree add -b {{var}} {{worktree_path}} <base>`, `<base>` must already
/// be a plain word ([`portable_shell_word`] leaves it unchanged); otherwise it is refused.
fn upgrade_legacy_worktree_path<'a>(
    command: &'a str,
    directory: Option<&str>,
) -> Result<Cow<'a, str>, String> {
    let Some(directory) = directory else {
        return Ok(Cow::Borrowed(command));
    };
    let worktree_path_var = handlebars_placeholder(WORKTREE_PATH_VAR);
    let mut command = Cow::Borrowed(command);
    for branch_var in [AUTOGENERATED_BRANCH_NAME_PARAM, WORKTREE_BRANCH_NAME_PARAM] {
        let legacy = format!(
            "\"{}\"",
            generated_worktree_path_string(
                Path::new(directory),
                &handlebars_placeholder(branch_var)
            )
        );
        if !command.contains(&legacy) {
            continue;
        }
        command = Cow::Owned(command.replace(&legacy, &worktree_path_var));
        let legacy_add = format!(
            "git worktree add -b {} {worktree_path_var}",
            handlebars_placeholder(branch_var)
        );
        if let Some(tail) = command.strip_prefix(&legacy_add) {
            let base = tail.trim();
            if !base.is_empty() && portable_shell_word(base).as_deref() != Some(base) {
                return Err(format!(
                    "this worktree config was created by an older version and passes the base \
                     branch {base:?} to the shell unquoted; recreate the config"
                ));
            }
        }
    }
    Ok(command)
}

/// Quote characters in any supported shell, including the typographic ones PowerShell accepts.
const QUOTE_CHARS: [char; 9] = [
    '\'', '"', '\u{2018}', '\u{2019}', '\u{201A}', '\u{201B}', '\u{201C}', '\u{201D}', '\u{201E}',
];

/// Stands for a substituted placeholder in the residual command text that
/// [`render_command`] checks: a private-use character no template plausibly contains.
const PLACEHOLDER_MARK: char = '\u{E000}';
/// Stands for a literal quoted string in the residual text the syntax checks see.
const LITERAL_MARK: char = '\u{E001}';

/// The residual command in the two forms [`render_command`] checks.
struct StrippedCommand {
    /// Each quoted literal replaced by [`LITERAL_MARK`]: for the syntax checks, which must not
    /// look inside a literal (`'$(id)'` is inert).
    marked: Vec<char>,
    /// Each quoted literal replaced by its content, with whitespace and `; & | ( )` in it
    /// mapped to `_`: for the word-level checks, which must see the word the shell runs —
    /// `'ssh'`, `s'sh'` and `e''val` are `ssh` and `eval`, while `'a;ssh;b'` stays the one
    /// harmless word `a_ssh_b`.
    words: Vec<char>,
}

/// Checks the quoted literals in `residual`, or says why one is unsafe.
///
/// A quoted string is allowed next to substituted placeholders only when it is a closed
/// literal that every shell reads the same way and that contains no placeholder — exactly the
/// two forms [`portable_shell_word`] itself writes, which generated commands bake in (the base
/// branch of `git worktree add`): `'...'` without a backslash or typographic single quote, and
/// `"..."` without `$`, `` ` ``, `\`, `!` or a typographic double quote. With every quote
/// pair such a literal, no substituted word can sit inside quotes in any shell. Anything else
/// — an unclosed quote, a placeholder or line break inside quotes, a typographic quote outside
/// one — is refused.
fn strip_literal_quoted_strings(residual: &[char]) -> Result<StrippedCommand, &'static str> {
    let mut marked = Vec::with_capacity(residual.len());
    let mut words = Vec::with_capacity(residual.len());
    let mut index = 0;
    while index < residual.len() {
        let c = residual[index];
        let forbidden_inside: &[char] = match c {
            '\'' => &['\\', '\u{2018}', '\u{2019}', '\u{201A}', '\u{201B}'],
            '"' => &['$', '`', '\\', '!', '\u{201C}', '\u{201D}', '\u{201E}'],
            c if QUOTE_CHARS.contains(&c) => return Err("a typographic quote"),
            c => {
                marked.push(c);
                words.push(c);
                index += 1;
                continue;
            }
        };
        let Some(length) = residual[index + 1..].iter().position(|&next| next == c) else {
            return Err("an unclosed quote");
        };
        let content = &residual[index + 1..index + 1 + length];
        if content.contains(&PLACEHOLDER_MARK) {
            return Err("a placeholder inside quotes");
        }
        if content
            .iter()
            .any(|&inner| inner == '\n' || inner == '\r' || forbidden_inside.contains(&inner))
        {
            return Err("quotes whose content the shells read differently");
        }
        marked.push(LITERAL_MARK);
        words.extend(content.iter().map(|&inner| {
            if inner.is_whitespace() || matches!(inner, ';' | '&' | '|' | '(' | ')') {
                '_'
            } else {
                inner
            }
        }));
        index += length + 2;
    }
    Ok(StrippedCommand { marked, words })
}

/// Shell syntax that a command with a substituted placeholder must not contain anywhere: a
/// substituted word is quoted for "an ordinary argument word", and each of these opens a
/// context where that quoting no longer means what it says (#878). `residual` is the
/// [`StrippedCommand::marked`] form.
fn forbidden_syntax_around_placeholders(residual: &[char]) -> Option<&'static str> {
    let text: String = residual.iter().collect();
    for (needle, what) in [
        ("$(", "`$(...)`"),
        ("${", "`${...}`"),
        ("$[", "`$[...]` arithmetic"),
        ("(e:", "a zsh `(e:...)` glob qualifier"),
        ("((", "`((...))`"),
        ("<<", "a heredoc"),
        ("--%", "PowerShell's `--%` stop-parsing token"),
    ] {
        if text.contains(needle) {
            return Some(what);
        }
    }
    let mut bracket_depth = 0usize;
    for (index, &c) in residual.iter().enumerate() {
        let what = match c {
            '\n' | '\r' => "a line break",
            '`' => "a backtick",
            '\\' => "a backslash",
            c if QUOTE_CHARS.contains(&c) => "quotes",
            '#' if index == 0
                || residual[index - 1].is_whitespace()
                || matches!(residual[index - 1], ';' | '&' | '|' | '(' | ')' | '<' | '>') =>
            {
                "a comment"
            }
            '[' => {
                bracket_depth += 1;
                continue;
            }
            ']' => {
                bracket_depth = bracket_depth.saturating_sub(1);
                continue;
            }
            // Inside `[...]` — a subscript, `[ ... ]`/`[[ ... ]]` test or glob class — a
            // word may be evaluated as arithmetic or a pattern.
            PLACEHOLDER_MARK if bracket_depth > 0 => "a placeholder inside `[...]`",
            _ => continue,
        };
        return Some(what);
    }
    None
}

/// Commands that parse their arguments as shell (or PowerShell / cmd) code again, where a
/// value quoted for the local shell is unquoted text: `ssh host {{x}}` runs `{{x}}`'s value on
/// the remote shell. Also the cheap arithmetic and variable-name cases: `let`, `read`,
/// `declare`/`typeset`/`local`, `printf -v`, `test`/`[`/`[[` with `-v` or a numeric
/// comparison, and a `$variable` as the command name. Best-effort, word-level: the first word
/// of each `;`/`&`/`|`/`(`-separated segment (after `VAR=value` assignments and a path), plus
/// the flags that make a command re-parse (`sh -c`, `docker exec`, `find -exec`,
/// `git -c alias.*`, `cmd /c`, ...). `residual` is the [`StrippedCommand::words`] form, so a
/// quoted command name is seen unquoted. It cannot see aliases, functions or scripts that do
/// the same, which is why the docs say never to pass a placeholder to anything that re-parses
/// it.
fn reparsing_command(residual: &[char]) -> Option<&'static str> {
    const ALWAYS: [&str; 15] = [
        "ssh",
        "eval",
        "watch",
        "tmux",
        "screen",
        "su",
        "xargs",
        "trap",
        "iex",
        "invoke-expression",
        "invoke-command",
        "start-process",
        "let",
        "read",
        "source",
    ];
    const SHELLS: [&str; 7] = ["sh", "bash", "zsh", "fish", "dash", "ksh", "pwsh"];
    const PREFIXES: [&str; 8] = [
        "sudo", "doas", "env", "nohup", "time", "nice", "command", "exec",
    ];
    const COMPARISONS: [&str; 7] = ["-eq", "-ne", "-lt", "-le", "-gt", "-ge", "-v"];

    let text: String = residual
        .iter()
        .map(|&c| {
            if matches!(c, ';' | '&' | '|' | '(' | ')') {
                '\n'
            } else {
                c
            }
        })
        .collect();
    for segment in text.lines() {
        let mut raw_words = segment.split_whitespace().skip_while(|word| {
            word.split_once('=').is_some_and(|(name, _)| {
                !name.is_empty() && name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')
            })
        });
        let Some(raw_first) = raw_words.next() else {
            continue;
        };
        if raw_first.starts_with('$') {
            return Some("a variable as the command name");
        }
        let words: Vec<String> = std::iter::once(raw_first)
            .chain(raw_words)
            .map(|word| {
                let base = word
                    .rsplit(|c: char| c == '/' || c == '\\')
                    .next()
                    .unwrap_or(word);
                let base = base.to_ascii_lowercase();
                base.strip_suffix(".exe")
                    .map(str::to_string)
                    .unwrap_or(base)
            })
            .collect();
        let first = words[0].as_str();
        let rest = &words[1..];
        let has = |flag: &str| rest.iter().any(|word| word == flag);
        let has_shell_c = |words: &[String]| {
            words
                .iter()
                .position(|word| SHELLS.contains(&word.as_str()))
                .is_some_and(|i| {
                    words[i + 1..].iter().any(|word| {
                        word.starts_with('-') && !word.starts_with("--") && word.contains('c')
                    })
                })
        };
        let has_powershell_command = |words: &[String]| {
            words
                .iter()
                .position(|word| matches!(word.as_str(), "powershell" | "pwsh"))
                .is_some_and(|i| {
                    words[i + 1..]
                        .iter()
                        .any(|word| word.starts_with("-c") || word.starts_with("-e"))
                })
        };
        let has_cmd_c = |words: &[String]| {
            words
                .iter()
                .position(|word| word == "cmd")
                .is_some_and(|i| {
                    words[i + 1..]
                        .iter()
                        .any(|word| word.starts_with("/c") || word.starts_with("/k"))
                })
        };
        let reparses = ALWAYS.contains(&first)
            || has_shell_c(&words[..])
            || has_powershell_command(&words[..])
            || has_cmd_c(&words[..])
            || (PREFIXES.contains(&first)
                && (rest.iter().any(|word| ALWAYS.contains(&word.as_str()))
                    || has("-c")
                    || has_shell_c(rest)))
            || (matches!(first, "docker" | "podman" | "kubectl") && has("exec"))
            || (first == "find"
                && ["-exec", "-execdir", "-ok", "-okdir"]
                    .iter()
                    .copied()
                    .any(|flag| has(flag)))
            || (first == "script" && has("-c"))
            || (first == "git" && rest.iter().any(|word| word.starts_with("alias.")));
        if reparses {
            return Some("a command that parses its arguments as shell code again");
        }
        let arithmetic_or_name = matches!(first, "declare" | "typeset" | "local")
            || (first == "printf" && has("-v"))
            || (matches!(first, "test" | "[" | "[[")
                && COMPARISONS.iter().copied().any(|flag| has(flag)));
        if arithmetic_or_name {
            return Some("a command that reads its arguments as arithmetic or variable names");
        }
    }
    None
}

/// Renders one command template, substituting each referenced value as a single shell word
/// spelled by [`portable_shell_word`]. Placeholders without a value are left as they are.
///
/// The word's quoting is only right where a shell reads an ordinary argument word, and this
/// does not parse shell to find out where that is. Instead a command with any substituted
/// placeholder is held to a conservative whitelist (#878): a placeholder written as exactly
/// `"{{x}}"` or `'{{x}}'` has that quote pair dropped; any other quoted string must be a closed
/// literal with no placeholder inside (see [`strip_literal_quoted_strings`] — the form
/// generated commands bake the base branch in); outside those literals the command must
/// contain no `$(`, `${`, `$[`, `((`, `<<`, `(e:`, backtick, backslash, line break or
/// word-initial `#`, no `$` or `[` directly before a placeholder, and no command that
/// re-parses its arguments ([`reparsing_command`]). Anything else is an
/// error naming the placeholders: quotes around or near the placeholder, command
/// substitution, parameter expansion, arithmetic, heredocs and comments all change what the
/// substituted quoting means, and the shells disagree on them. A value with no portable
/// spelling is an error too. Commands without substituted placeholders are not restricted.
pub(crate) fn render_command(
    template: &str,
    values: &HashMap<String, String>,
) -> Result<String, String> {
    use handlebars::parser::{ParsedArgumentResult, ParsedArgumentsIterator};

    let chars: Vec<char> = template.chars().collect();
    // (start, end, word, description): the chars `start..end` — the placeholder and any
    // exact wrapping quote pair — are replaced by `word`.
    let mut spans: Vec<(usize, usize, String, String)> = Vec::new();
    for parsed in ParsedArgumentsIterator::new(template.chars()) {
        if !matches!(parsed.result(), ParsedArgumentResult::Valid { .. }) {
            continue;
        }
        let name_range = parsed.chars_range();
        // Same guard as `handlebars::render_template`: a valid argument has two braces each side.
        if name_range.start < 2 {
            continue;
        }
        let name: String = chars[name_range.clone()].iter().collect();
        let Some(value) = values.get(&name) else {
            continue;
        };
        let word = portable_shell_word(value).ok_or_else(|| {
            format!(
                "the value of `{name}` ({value:?}) has no quoting that every supported shell \
                 reads the same way"
            )
        })?;

        let (mut start, mut end) = (name_range.start - 2, name_range.end + 2);
        let previous_end = spans.last().map_or(0, |span| span.1);
        if start > previous_end
            && matches!(chars[start - 1], '\'' | '"')
            && chars.get(end) == Some(&chars[start - 1])
        {
            start -= 1;
            end += 1;
        }
        // After `$`, bash/zsh read a quoted word as `$'...'`/`$"..."` and fish rejects it;
        // after `[` it is an array subscript (`arr[...]`, zsh `h[...]`), evaluated as
        // arithmetic or a pattern.
        if start > 0 && matches!(chars[start - 1], '$' | '[') {
            return Err(format!(
                "`{{{{{name}}}}}` directly follows `{}` in the command {template:?}, so its \
                 value ({value:?}) cannot be quoted safely",
                chars[start - 1]
            ));
        }
        spans.push((
            start,
            end,
            word.into_owned(),
            format!("`{{{{{name}}}}}` ({value:?})"),
        ));
    }
    if spans.is_empty() {
        return Ok(template.to_string());
    }

    // The command with every substituted span replaced by `PLACEHOLDER_MARK`.
    let mut residual = Vec::with_capacity(chars.len());
    let mut cursor = 0;
    for (start, end, _, _) in &spans {
        residual.extend_from_slice(&chars[cursor..*start]);
        residual.push(PLACEHOLDER_MARK);
        cursor = *end;
    }
    residual.extend_from_slice(&chars[cursor..]);
    let checked = strip_literal_quoted_strings(&residual).and_then(|stripped| {
        match forbidden_syntax_around_placeholders(&stripped.marked)
            .or_else(|| reparsing_command(&stripped.words))
        {
            Some(what) => Err(what),
            None => Ok(()),
        }
    });
    if let Err(what) = checked {
        let names = spans
            .iter()
            .map(|(_, _, _, description)| description.as_str())
            .collect::<Vec<_>>()
            .join(", ");
        return Err(format!(
            "the command {template:?} substitutes {names} but also contains {what}, which a \
             substituted value cannot be quoted safely around; use each placeholder as a plain \
             word outside any quotes (`cd {{{{name}}}}`), with no `$(...)`, `${{...}}`, \
             backticks, backslashes, heredocs, comments or line breaks in the same command"
        ));
    }

    let mut out = String::with_capacity(template.len());
    let mut cursor = 0;
    for (start, end, word, _) in &spans {
        out.extend(&chars[cursor..*start]);
        out.push_str(word);
        cursor = *end;
    }
    out.extend(&chars[cursor..]);
    Ok(out)
}

// ── Flat pane tree resolution ───────────────────────────────────────

/// Builds a [`PaneTemplateType`] tree from a flat `[[panes]]` list.
///
/// The first entry is the root.  Split nodes reference children by ID;
/// leaf nodes produce terminal panes.
fn resolve_pane_tree(
    panes: &[TabConfigPaneNode],
    context: &HashMap<String, String>,
) -> Result<PaneTemplateType, ResolveError> {
    if panes.is_empty() {
        return Err("panes array is empty".to_string().into());
    }

    let pane_map: HashMap<&str, &TabConfigPaneNode> =
        panes.iter().map(|p| (p.id.as_str(), p)).collect();

    if pane_map.len() != panes.len() {
        return Err("duplicate pane IDs detected".to_string().into());
    }

    let root = &panes[0];
    let has_explicit_focus = panes
        .iter()
        .any(|p| p.split.is_none() && p.is_focused == Some(true));

    let (template, _) = resolve_pane_node(
        root,
        &pane_map,
        context,
        !has_explicit_focus, // auto-focus first leaf when nothing is explicitly focused
    )?;

    Ok(template)
}

/// Recursively resolves a single pane node.
///
/// Returns `(PaneTemplateType, did_consume_auto_focus)` — the second element
/// is `true` when a leaf consumed the auto-focus so subsequent leaves are not
/// also focused.
fn resolve_pane_node(
    node: &TabConfigPaneNode,
    pane_map: &HashMap<&str, &TabConfigPaneNode>,
    context: &HashMap<String, String>,
    auto_focus_first_leaf: bool,
) -> Result<(PaneTemplateType, bool), ResolveError> {
    if let Some(split_direction) = &node.split {
        // ── Split node ──────────────────────────────────────────────
        let children = node
            .children
            .as_ref()
            .ok_or_else(|| format!("split node '{}' is missing 'children'", node.id))?;

        if children.len() < 2 {
            return Err(format!(
                "split node '{}' must have at least 2 children, got {}",
                node.id,
                children.len()
            )
            .into());
        }

        let mut child_templates = Vec::with_capacity(children.len());
        let mut auto_focus_remaining = auto_focus_first_leaf;

        for child_id in children {
            let child = pane_map.get(child_id.as_str()).ok_or_else(|| {
                format!(
                    "split node '{}' references unknown child '{}'",
                    node.id, child_id
                )
            })?;
            let (child_template, did_focus) =
                resolve_pane_node(child, pane_map, context, auto_focus_remaining)?;
            if did_focus {
                auto_focus_remaining = false;
            }
            child_templates.push(child_template);
        }

        Ok((
            PaneTemplateType::PaneBranchTemplate {
                split_direction: split_direction.clone(),
                panes: child_templates,
            },
            auto_focus_first_leaf && !auto_focus_remaining,
        ))
    } else {
        // ── Leaf node ────────────────────────────────────────────────
        let pane_type = node
            .pane_type
            .as_ref()
            .ok_or_else(|| format!("leaf pane '{}' is missing required 'type' field", node.id))?;

        let pane_mode = match pane_type {
            TabConfigPaneType::Terminal => PaneMode::Terminal,
            TabConfigPaneType::Agent => PaneMode::Agent,
        };

        let directory = node
            .directory
            .as_deref()
            .map(|c| handlebars::render_template(c, context));
        let cwd = directory
            .as_deref()
            .map(|rendered| PathBuf::from(shellexpand::tilde(rendered).into_owned()))
            .unwrap_or_default();

        let command_values = command_values_for_pane(context, directory.as_deref());
        let commands: Vec<CommandTemplate> = node
            .commands
            .as_deref()
            .unwrap_or_default()
            .iter()
            .map(|cmd| {
                upgrade_legacy_worktree_path(cmd, directory.as_deref())
                    .and_then(|cmd| render_command(&cmd, &command_values))
                    .map(|exec| CommandTemplate { exec })
                    .map_err(|err| {
                        ResolveError::UnsafeCommand(format!("pane '{}': {err}", node.id))
                    })
            })
            .collect::<Result<_, _>>()?;

        let explicitly_focused = node.is_focused == Some(true);
        let is_focused = explicitly_focused || auto_focus_first_leaf;
        let did_consume = is_focused && !explicitly_focused;

        Ok((
            PaneTemplateType::PaneTemplate {
                cwd,
                commands,
                is_focused: Some(is_focused),
                pane_mode,
                shell: node.shell.clone(),
            },
            explicitly_focused || did_consume,
        ))
    }
}

/// Builds a worktree tab config TOML string.
///
/// When `worktree_branch_name` is `Some(name)` (manual naming), the returned
/// TOML bakes commands with Handlebars template variables and exposes a
/// `worktree_branch_name` param so re-opens show the params modal.
///
/// When `None` (autogenerate), the TOML stores commands with
/// `{{autogenerated_branch_name}}` Handlebars template variables that get
/// substituted with a fresh name on every open.
///
/// Nothing derived from the repository is written into the command text: the worktree path
/// (which contains the repo directory's name) is the render-time `{{worktree_path}}` and is
/// quoted when the config is opened. The base branch is the one value baked in, as a single
/// [`portable_shell_word`] after `--`; a branch name with no portable spelling, or one that
/// contains a `{{`/`}}` the later render would substitute into, is refused (#878).
#[cfg(feature = "local_fs")]
pub(crate) fn build_worktree_config_toml(
    config_name: &str,
    repo: &str,
    base_branch: &str,
    worktree_branch_name: Option<&str>,
) -> Result<String, String> {
    let mut doc = toml::map::Map::new();
    doc.insert("name".into(), Value::String(config_name.to_string()));

    let mut pane = toml::map::Map::new();
    pane.insert("id".into(), Value::String("main".into()));
    pane.insert("type".into(), Value::String("terminal".into()));
    pane.insert("directory".into(), Value::String(repo.to_string()));

    let branch_var = if worktree_branch_name.is_some() {
        WORKTREE_BRANCH_NAME_PARAM
    } else {
        AUTOGENERATED_BRANCH_NAME_PARAM
    };
    let commands = worktree_setup_commands(branch_var, Some(base_branch))?;
    pane.insert(
        "commands".into(),
        Value::Array(commands.into_iter().map(Value::String).collect()),
    );
    doc.insert("panes".into(), Value::Array(vec![Value::Table(pane)]));

    if worktree_branch_name.is_some() {
        doc.insert(
            "title".into(),
            Value::String(handlebars_placeholder(WORKTREE_BRANCH_NAME_PARAM)),
        );
        let mut param = toml::map::Map::new();
        param.insert("type".into(), Value::String("text".into()));
        param.insert(
            "description".into(),
            Value::String("Worktree branch name".to_string()),
        );
        let mut params = toml::map::Map::new();
        params.insert(WORKTREE_BRANCH_NAME_PARAM.into(), Value::Table(param));
        doc.insert("params".into(), Value::Table(params));
    }

    Ok(toml::to_string_pretty(&Value::Table(doc)).expect("generated TOML should always serialize"))
}

/// The commands that create a worktree for the branch held in `branch_var` and enter it:
/// `git worktree add -b {{branch_var}} -- {{worktree_path}} [<base>]` and
/// `cd {{worktree_path}}`.
///
/// `--` ends git's option parsing, so a base branch (or, defensively, a path) that starts
/// with `-` is a positional argument; `-b` always takes the next word as its value. An empty
/// `base_branch` is omitted, leaving git to use `HEAD`.
pub(crate) fn worktree_setup_commands(
    branch_var: &str,
    base_branch: Option<&str>,
) -> Result<Vec<String>, String> {
    let branch = handlebars_placeholder(branch_var);
    let worktree_path = handlebars_placeholder(WORKTREE_PATH_VAR);
    let mut add = format!("git worktree add -b {branch} -- {worktree_path}");
    if let Some(base_branch) = base_branch.filter(|base| !base.is_empty()) {
        if base_branch.contains("{{") || base_branch.contains("}}") {
            return Err(format!(
                "base branch {base_branch:?} contains a template brace pair; refusing to create \
                 the worktree config"
            ));
        }
        let word = portable_shell_word(base_branch).ok_or_else(|| {
            format!(
                "base branch {base_branch:?} has no quoting that every supported shell reads the \
                 same way; refusing to create the worktree config"
            )
        })?;
        add.push(' ');
        add.push_str(&word);
    }
    Ok(vec![add, format!("cd {worktree_path}")])
}

