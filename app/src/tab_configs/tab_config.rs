pub(crate) const AUTOGENERATED_BRANCH_NAME_PARAM: &str = "autogenerated_branch_name";

// Rust `format!` treats `{...}` as interpolation syntax, so we escape braces
// to emit the literal Handlebars placeholder `{{name}}` for the later
// tab-config render pass. In `format!("{{{{{name}}}}}")`, the outer doubled
// braces become literal `{` / `}`, and `{name}` interpolates the helper arg.
pub(crate) fn handlebars_placeholder(name: &str) -> String {
    format!("{{{{{name}}}}}")
}

pub(crate) fn generated_worktree_repo_dir(repo_path: &Path) -> PathBuf {
    let repo_name = repo_path
        .file_name()
        .and_then(|name| name.to_str())
        .filter(|name| !name.is_empty())
        .unwrap_or("untitled");
    warp_core::paths::data_dir()
        .join("worktrees")
        .join(repo_name)
}
pub(crate) fn generated_worktree_path(repo_path: &Path, worktree_name: &str) -> PathBuf {
    generated_worktree_repo_dir(repo_path).join(worktree_name)
}
pub(crate) fn generated_worktree_path_string(repo_path: &Path, worktree_name: &str) -> String {
    generated_worktree_path(repo_path, worktree_name)
        .display()
        .to_string()
}

/// Render-time variable holding the generated worktree path
/// (`<data dir>/worktrees/<repo name>/<branch>`) for the pane's directory.
///
/// Generated worktree commands reference the path through this variable instead of baking it
/// into the command text, so the path — which contains the repository directory's name — is
/// quoted as a whole by [`portable_shell_word`] at render time like any other value (#878).
pub(crate) const WORKTREE_PATH_VAR: &str = "worktree_path";

/// The param holding a manually named worktree branch.
pub(crate) const WORKTREE_BRANCH_NAME_PARAM: &str = "worktree_branch_name";

/// Spells `value` as one shell word with the same meaning in bash, zsh, fish and PowerShell,
/// or returns `None` when no such spelling exists (#878).
///
/// Tab config commands are rendered before the pane's shell exists — `shell = ...` may name
/// any shell, the default may be the OS's choice, and a saved config is replayed in whatever
/// shell is current when it is reopened — so the session's [`warp_util::path::ShellDialect`]
/// is not known here. Values are therefore written in a form all four shells parse alike:
/// * bare, when every character is an ASCII letter, digit, `_`, `.`, `/`, `-` or `:` and the
///   word starts with a letter, `_` or `/` (PowerShell reads a leading `-` as a parameter name
///   and a leading digit as a number literal: `1kb` is 1024);
/// * single-quoted, when the value has no `'` (nor PowerShell's typographic single quotes) and
///   no backslash that fish would treat as an escape inside single quotes (`\\`, or a trailing
///   `\` that would escape the closing quote);
/// * double-quoted, when the value has none of `$`, `` ` ``, `"`, `\`, `!` (history expansion
///   in interactive bash/zsh) or PowerShell's typographic double quotes.
///
/// Control characters (see [`needs_control_char_quoting`]) have no common spelling and would
/// reach the PTY raw (#867), so they always yield `None`. Callers must refuse to run a
/// command whose value cannot be spelled rather than fall back to a single shell's quoting.
pub(crate) fn portable_shell_word(value: &str) -> Option<Cow<'_, str>> {
    if value.chars().any(needs_control_char_quoting) {
        return None;
    }
    let is_bare_char =
        |c: char| c.is_ascii_alphanumeric() || matches!(c, '_' | '.' | '/' | '-' | ':');
    let is_bare_start = |c: char| c.is_ascii_alphabetic() || matches!(c, '_' | '/');
    if value.starts_with(is_bare_start) && value.chars().all(is_bare_char) {
        return Some(Cow::Borrowed(value));
    }
    let has_single_quote = value
        .chars()
        .any(|c| matches!(c, '\'' | '\u{2018}' | '\u{2019}' | '\u{201A}' | '\u{201B}'));
    if !has_single_quote && !value.contains("\\\\") && !value.ends_with('\\') {
        return Some(Cow::Owned(format!("'{value}'")));
    }
    let has_double_quote_special = value.chars().any(|c| {
        matches!(
            c,
            '$' | '`' | '"' | '\\' | '!' | '\u{201C}' | '\u{201D}' | '\u{201E}'
        )
    });
    if !has_double_quote_special {
        return Some(Cow::Owned(format!("\"{value}\"")));
    }
    None
}

/// The kind of smart picker to show for a parameter.
///
/// Authors opt in via `type = "branch"` or `type = "repo"` in the TOML.
/// Omitting the field (or using `type = "text"`) gives a plain text editor.
#[derive(Clone, Debug, Default, Deserialize, Serialize, PartialEq, Eq)]
#[serde(rename_all = "snake_case")]
pub enum TabConfigParamType {
    /// A plain single-line text editor (the default).
    #[default]
    Text,
    /// A dropdown populated with local git branches from the active terminal's repo.
    Branch,
    /// A dropdown populated with known repos (from the project list), with an option to add a new one.
    Repo,
}

/// A single parameter declared in a tab config file.
#[derive(Clone, Debug, Deserialize, Serialize)]
#[serde(deny_unknown_fields)]
pub struct TabConfigParam {
    /// Human-readable description shown in the param-fill UI.
    #[serde(default)]
    pub description: Option<String>,
    /// Default value used when the user provides no input.
    #[serde(default)]
    pub default: Option<String>,
    /// Controls which smart picker to render for this param.
    ///
    /// Defaults to `TabConfigParamType::Text` (a plain text input).
    #[serde(default, rename = "type")]
    pub param_type: TabConfigParamType,
}

