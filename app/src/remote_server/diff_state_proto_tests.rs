//! Round-trip and mapping tests for the diff-state proto conversions.

use std::path::PathBuf;
use std::sync::Arc;

use super::*;
use crate::code_review::diff_size_limits::DiffSize;
use crate::code_review::diff_state::{
    DiffHunk, DiffLine, DiffLineType, DiffMode, DiffState, FileDiff, FileStatusInfo, GitDiffData,
    GitFileStatus,
};
use crate::util::git::{Commit, FileChangeEntry, PrInfo};

fn sample_line(line_type: DiffLineType) -> DiffLine {
    DiffLine {
        line_type,
        old_line_number: Some(3),
        new_line_number: None,
        text: "let x = 1;".to_string(),
        no_trailing_newline: true,
    }
}

fn sample_hunk() -> DiffHunk {
    DiffHunk {
        old_start_line: 10,
        old_line_count: 2,
        new_start_line: 10,
        new_line_count: 3,
        lines: vec![
            sample_line(DiffLineType::Context),
            sample_line(DiffLineType::Add),
            sample_line(DiffLineType::Delete),
        ],
        unified_diff_start: 100,
        unified_diff_end: 140,
    }
}

fn sample_file_diff() -> FileDiff {
    FileDiff {
        file_path: PathBuf::from("src/main.rs"),
        status: GitFileStatus::Renamed {
            old_path: "src/old.rs".to_string(),
        },
        hunks: Arc::new(vec![sample_hunk()]),
        is_binary: false,
        is_autogenerated: false,
        max_line_number: 42,
        has_hidden_bidi_chars: false,
        size: DiffSize::Normal,
    }
}

#[test]
fn diff_line_round_trips_all_types() {
    for lt in [
        DiffLineType::Context,
        DiffLineType::Add,
        DiffLineType::Delete,
        DiffLineType::HunkHeader,
    ] {
        let original = sample_line(lt);
        let back = proto_to_diff_line(&diff_line_to_proto(&original));
        assert_eq!(original, back);
    }
}

#[test]
fn diff_line_type_unspecified_falls_back_to_context() {
    // Wire value 0 (UNSPECIFIED) is never produced by us but must decode safely.
    assert_eq!(proto_to_diff_line_type(0), DiffLineType::Context);
}

