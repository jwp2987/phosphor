#[test]
fn commit_round_trips_forks_fields_and_encodes_empty_files() {
    let original = Commit {
        hash: "abc123".to_string(),
        subject: "fix: thing".to_string(),
        files_changed: 3,
        additions: 20,
        deletions: 8,
    };
    let encoded = commit_to_proto(&original);
    // The fork has no per-file list; it must encode empty (not fabricated).
    assert!(encoded.files.is_empty());
    let back = proto_to_commit(&encoded);
    assert_eq!(original, back);
}

#[test]
fn pr_info_round_trips_forks_fields_and_defaults_extras() {
    let original = PrInfo {
        number: 42,
        url: "https://example.com/pr/42".to_string(),
    };
    let encoded = pr_info_to_proto(&original);
    assert_eq!(encoded.state, "");
    assert!(!encoded.draft);
    assert_eq!(encoded.base_branch, "");
    let back = proto_to_pr_info(&encoded);
    assert_eq!(original, back);
}
