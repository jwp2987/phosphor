#[test]
fn diff_state_maps_variants_and_folds_payload() {
    // Non-loaded variants carry no payload.
    match proto_to_diff_state(&diff_state_to_proto(&DiffState::NotInRepository), None) {
        DiffState::NotInRepository => {}
        _ => panic!("expected NotInRepository"),
    }
    match proto_to_diff_state(&diff_state_to_proto(&DiffState::Loading), None) {
        DiffState::Loading => {}
        _ => panic!("expected Loading"),
    }
    match proto_to_diff_state(
        &diff_state_to_proto(&DiffState::Error("boom".to_string())),
        None,
    ) {
        DiffState::Error(msg) => assert_eq!(msg, "boom"),
        _ => panic!("expected Error"),
    }

    // Loaded folds the separately-carried diffs payload back in.
    let diffs = GitDiffData {
        files: vec![sample_file_diff()],
        total_additions: 1,
        total_deletions: 0,
        files_changed: 1,
    };
    let proto_state = diff_state_to_proto(&DiffState::Loaded(diffs.clone()));
    match proto_to_diff_state(&proto_state, Some(diffs.clone())) {
        DiffState::Loaded(back) => assert_eq!(back, diffs),
        _ => panic!("expected Loaded"),
    }
}

